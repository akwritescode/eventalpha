"""Render the SQL demo from the same fixture imported by the UI. No network access."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def literal(value: str | None) -> str:
    return "NULL" if value is None else "'" + value.replace("'", "''") + "'"


def render() -> str:
    demo = json.loads((ROOT / "web/src/fixtures/move-demo.json").read_text())
    article = demo["article"]
    values = [article[key] for key in ("source", "source_id", "form_type", "url", "title")]
    values += [
        "{" + demo["ticker"] + "}",
        article["published_at"],
        article["ingested_at"],
        article["ingested_at"],
        article["content_hash"],
    ]
    sql = (
        """-- Generated by scripts/render_move_demo.py from web/src/fixtures/move-demo.json.
-- Local demo only: real filing, synthetic X IDs and observation times. Never load on a live warehouse.

INSERT INTO articles (source, source_id, form_type, url, title, tickers, published_at, ingested_at,
                      updated_at, content_hash)
VALUES ("""
        + ", ".join(map(literal, values))
        + ")\nON CONFLICT (source, source_id) DO NOTHING;\n"
    )
    for lead in demo["leads"]:
        verified = lead["verified_at"] is not None
        values = [lead["post_id"], demo["ticker"], lead["paraphrase"], lead["published_at"], lead["first_seen_at"]]
        selected = ", ".join(map(literal, values))
        selected += ", a.id, a.content_hash, " + literal(lead["verified_at"]) if verified else ", NULL, NULL, NULL"
        sql += (
            """
INSERT INTO x_leads (post_id, ticker, paraphrase, published_at, first_seen_at, article_id,
                     article_content_hash, verified_at)
SELECT """
            + selected
            + "\nFROM articles a WHERE source = "
            + literal(article["source"])
        )
        sql += " AND source_id = " + literal(article["source_id"]) + "\nON CONFLICT (post_id) DO NOTHING;\n"
    return sql


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "examples/move-window.sql"
    expected = render()
    if args.check:
        if target.read_text() != expected:
            parser.exit(1, "Demo SQL is stale: run python scripts/render_move_demo.py\n")
    else:
        target.write_text(expected)
